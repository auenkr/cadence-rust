#!/usr/bin/env python3
"""Generate explicit protobuf -> Rust decision adapters for represented types.
Reject nondefault protobuf fields that the Rust engine cannot represent yet.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[2]
source=(ROOT/'rust/crates/cadence-api/src/tasks.rs').read_text()
structs={n:dict((k,v.strip().rstrip(',')) for k,v in re.findall(r'pub (\w+):\s*([^\n]+)',b)) for n,b in re.findall(r'pub struct (\w+) \{(.*?)\n\}',source,re.S)}
proto=(ROOT/'go/idls/proto/uber/cadence/api/v1/decision.proto').read_text()
messages=dict(re.findall(r'message (\w+) \{(.*?)\n\}',proto,re.S))
def snake(n): return re.sub(r'(?<!^)(?=[A-Z])','_',n).lower()
out=['// Generated by rust/tools/generate-grpc-decisions.py; do not hand edit.','use cadence_api::{tasks, types as t, enums as e};','use cadence_proto::api as p;','use tonic::Status;','use crate::grpc_convert::*;']
attrs=[]
for name,fields in structs.items():
 if not name.endswith('DecisionAttributes') or name not in messages:continue
 attrs.append(name)
 pf=dict((field,typ) for typ,field in re.findall(r'^  ([\w.]+|map<[^>]+>) (\w+) = \d+',messages[name],re.M))
 used=set();lines=[]
 for field,typ in fields.items():
  source=field;expr=None
  aliases={'execution':'workflow_execution','backoff_start_interval_in_seconds':'backoff_start_interval'}
  source=aliases.get(field,field)
  if source.endswith('_seconds'):source=source.removesuffix('_seconds')
  if field in ['reason','details','failure_reason','failure_details'] and 'failure' in pf:
   used.add('failure');expr='v.failure.as_ref().map(|f|f.reason.clone())' if field.endswith('reason') else 'v.failure.as_ref().map(|f|f.details.clone()).unwrap_or_default()'
  elif name=='RequestCancelExternalWorkflowExecutionDecisionAttributes' and field in ['workflow_id','run_id']:
   used.add('workflow_execution');expr=f'v.workflow_execution.as_ref().map(|e|e.{field}.clone()).unwrap_or_default()'
  elif source in pf:
   used.add(source);f='v.'+source;pt=pf[source]
   if pt=='Payload':expr=f'data({f})'
   elif pt=='google.protobuf.Duration':expr=f'seconds({f})?' if typ=='Option<i32>' else f'{f}.map(|d|d.seconds)'
   elif pt=='WorkflowExecution':expr=f'{f}.map(execution)'
   elif pt=='WorkflowType':expr=f'{f}.map(|t|t::WorkflowType {{name:t.name}})'
   elif pt=='ActivityType':expr=f'{f}.map(|t|t::ActivityType {{name:t.name}})'
   elif pt=='TaskList':expr=f'{f}.map(task_list).transpose()?'
   elif pt=='RetryPolicy':expr=f'{f}.map(retry).transpose()?'
   elif pt in ['Header','Memo','SearchAttributes']:
    mapfield='indexed_fields' if pt=='SearchAttributes' else 'fields'
    expr=f'{f}.map(|m|t::{pt} {{{mapfield}:Some(m.{mapfield}.into_iter().map(|(k,p)|(k,p.data)).collect())}})'
   elif pt in ['string','bool','bytes','int32','int64']:expr=f
   else:
    etype=typ.removeprefix('Option<').removesuffix('>')
    expr=f'enum_in({f},e::{etype}::from_i32)?'
  if expr is None:raise RuntimeError(f'Unmapped field {name}.{field}')
  lines.append(f'        {field}: {expr},')
 checks=[]
 for field in sorted(pf.keys()-used):
  condition=f'v.{field}' if pf[field]=='bool' else f'v.{field}.is_some()'
  checks.append(f'    if {condition} {{return Err(Status::unimplemented("{name}.{field} has not been ported."));}}')
 out.extend([f'fn {snake(name)}(v:p::{name}) -> Result<tasks::{name},Status> {{',*checks,f'    Ok(tasks::{name} {{',*lines,'    })','}'])
out.extend(['pub fn decision(v:p::Decision) -> Result<tasks::Decision,Status> {','    let mut result=tasks::Decision::default();','    match v.attributes.ok_or_else(||Status::invalid_argument("Decision attributes are not set."))? {'])
for name in attrs:
 typ=name.removesuffix('DecisionAttributes');f=snake(name)
 out.extend([f'        p::decision::Attributes::{name}(v)=>{{',f'            result.decision_type=Some(e::DecisionType::{typ});',f'            result.{f}=Some({f}(v)?);','        }'])
out.extend(['        _=>return Err(Status::unimplemented("This decision type has not been ported.")),','    }','    Ok(result)','}'])
path=ROOT/'rust/crates/cadence-server/src/grpc_decisions.rs'
path.write_text('\n'.join(out)+'\n')
import subprocess
subprocess.run(['rustfmt','--edition','2021',str(path)],check=True)
