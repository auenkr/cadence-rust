#!/usr/bin/env python3
"""Generate frontend WorkflowService and Meta method IDs from pinned Thrift IDL.
IDL availability describes the wire schema, not engine implementation coverage.
"""
from pathlib import Path
import re
import subprocess
ROOT=Path(__file__).resolve().parents[2]
source=(ROOT/'go/idls/thrift/cadence.thrift').read_text()
source=re.sub(r'/\*.*?\*/','',source,flags=re.S)
source=re.sub(r'//[^\n]*','',source)
methods=re.findall(r'^\s*(?:void|shared\.\w+)\s+(\w+)\(([^)]*)\)\s*throws\s*\((.*?)\)',source,re.M|re.S)
if not methods:raise RuntimeError('No WorkflowService methods parsed')
output=['//! Generated by rust/tools/generate-thrift-methods.py from pinned cadence.thrift.','//! This is the full wire schema; unported handlers remain unsupported.','pub struct MethodDef {','    pub service: &\'static str,','    pub method: &\'static str,','    pub arg_type: &\'static str,','    pub exceptions: &\'static [(&\'static str, i16)],','}','pub const METHODS: &[MethodDef] = &[']
for name,args,errors in methods:
 arg=re.search(r'shared\.(\w+)',args)
 exceptions=', '.join(f'("{typ}", {number})' for number,typ in re.findall(r'(\d+)\s*:\s*shared\.(\w+)',errors))
 output.append(f'    MethodDef {{ service:"WorkflowService", method:"{name}", arg_type:"{arg[1] if arg else ""}", exceptions:&[{exceptions}] }},')
output.append('    MethodDef { service:"Meta", method:"health", arg_type:"", exceptions:&[] },')
output+= ['];', '''pub fn find_method(procedure:&str)->Option<&'static MethodDef> {
    match procedure.split_once("::") {
        Some((service,method)) => METHODS.iter().find(|definition|definition.service==service && definition.method==method),
        None => METHODS.iter().find(|definition|definition.method==procedure),
    }
}
pub fn exception_field(method:&MethodDef,exception:&str)->Option<i16> {
    method.exceptions.iter().find(|(name,_)|*name==exception).map(|(_,id)|*id)
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn no_argument_and_visibility_methods_use_upstream_exception_ids() {
        let attributes=find_method("WorkflowService::GetSearchAttributes").unwrap();
        assert_eq!(attributes.arg_type, "");
        assert_eq!(exception_field(attributes,"ServiceBusyError"),Some(2));
        assert_eq!(find_method("ListWorkflowExecutions").unwrap().arg_type,"ListWorkflowExecutionsRequest");
        assert!(find_method("UnsupportedProcedure").is_none());
        assert_eq!(find_method("Meta::health").unwrap().service,"Meta");
        assert!(find_method("WrongService::health").is_none());
        assert!(find_method("Meta::RegisterDomain").is_none());
    }
}''']
path=ROOT/'rust/crates/cadence-thrift/src/service.rs'
path.write_text('\n'.join(output)+'\n')
subprocess.run(['rustfmt','--edition','2021',str(path)],check=True)
print(f'Generated {len(methods)} WorkflowService definitions plus Meta::health')
