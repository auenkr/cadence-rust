#!/usr/bin/env python3
"""Generate explicit typed history adapters from the Rust and pinned IDL schemas.

Conversions mirror common/types/mapper/proto/api.go. Missing Rust fields remain
protobuf defaults; this generator does not invent engine behavior for them.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
structs = {}
for source in (ROOT / 'rust/crates/cadence-api/src').glob('*.rs'):
    for name, body in re.findall(r'pub struct (\w+) \{(.*?)\n\}', source.read_text(), re.S):
        fields = dict(re.findall(r'pub (\w+):\s*([^\n]+)', body))
        structs[name] = (source.stem, {k: v.rstrip(',').strip() for k, v in fields.items()})
proto = (ROOT / 'go/idls/proto/uber/cadence/api/v1/history.proto').read_text()
messages = dict(re.findall(r'message (\w+) \{(.*?)\n\}', proto, re.S))

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

out = ['// Generated by rust/tools/generate-grpc-history.py; do not hand edit.',
       '// Field/time/enum conversions follow Go common/types/mapper/proto/api.go.',
       'use cadence_api::{service_types as st, tasks, enums::EventType};',
       'use cadence_proto::api as p;', 'use tonic::Status;',
       'use crate::grpc_convert::*;']
attrs = []
for name, body in messages.items():
    if not name.endswith('EventAttributes') or name not in structs:
        continue
    module, fields = structs[name]
    namespace = 'st' if module == 'service_types' else 'tasks'
    attrs.append(name)
    lines = []
    used = set()
    for typ, field in re.findall(r'^  ([\w.]+|map<[^>]+>) (\w+) = \d+', body, re.M):
        source = field
        expression = None
        if typ == 'Failure':
            prefix = {'continued_failure': 'continued_failure_', 'last_failure': 'last_failure_'}.get(field, '')
            reason = prefix + 'reason'
            details = prefix + 'details'
            if field == 'failure' and 'failure_reason' in fields:
                reason, details = 'failure_reason', 'failure_details'
            options = prefix + 'options' if prefix else 'failure_options'
            if reason in fields:
                r = 'v.'+reason if fields[reason].startswith('Option') else 'Some(v.'+reason+')'
                d = 'v.'+details if details in fields else 'Vec::new()'
                o = 'v.'+options if options in fields else 'None'
                expression = f'failure({r}, {d}, {o})'
                used.update(k for k in [reason, details, options] if k in fields)
        elif typ == 'ParentExecutionInfo':
            expression = 'parent_info(v.parent_workflow_domain, v.parent_workflow_execution, v.parent_initiated_event_id)'
            used.update(['parent_workflow_domain', 'parent_workflow_execution', 'parent_initiated_event_id'])
        elif typ == 'ExternalExecutionInfo':
            expression = 'external_info(v.external_workflow_execution, v.external_initiated_event_id)'
            used.update(['external_workflow_execution', 'external_initiated_event_id'])
        else:
            aliases = {'expiration_time': 'expiration_timestamp', 'first_scheduled_time': 'first_scheduled_time_nano', 'first_run_at': 'first_run_at_timestamp', 'backoff_start_interval': 'backoff_start_interval_in_seconds'}
            source = aliases.get(field, field)
            if typ == 'google.protobuf.Duration' and source not in fields:
                source += '_seconds'
            if source in fields:
                used.add(source)
                f = 'v.'+source
                optional = fields[source].startswith('Option')
                if typ == 'Payload': expression = f'payload({f})'
                elif typ == 'google.protobuf.Duration': expression = f'{f}.map(duration)' if fields[source]=='Option<i64>' else f'{f}.map(|s|duration(s.into()))'
                elif typ == 'google.protobuf.Timestamp':
                    expression = f'{f}.map(timestamp_nanos)' if source.endswith('_nano') else f'{f}.map(timestamp)'
                elif typ in ['WorkflowType', 'ActivityType']: expression = f'{f}.map(|t|p::{typ} {{name:t.name}})'
                elif typ == 'TaskList': expression = f'{f}.map(task_list_out)'
                elif typ == 'WorkflowExecution': expression = f'{f}.map(execution_out)'
                elif typ == 'RetryPolicy': expression = f'{f}.map(retry_out)'
                elif typ == 'Memo': expression = f'{f}.map(memo)'
                elif typ == 'Header': expression = f'{f}.map(header)'
                elif typ == 'SearchAttributes': expression = f'{f}.map(search_attributes)'
                elif typ.startswith('map<'): expression = f'{f}.unwrap_or_default()' if optional else f
                elif typ in ['string','int64','int32','bytes','bool']:
                    expression = f'{f}.unwrap_or_default()' if optional else f
                    if typ == 'int32' and fields[source]=='i64': expression += ' as i32'
                else: expression = f'{f}.map_or(0,|e|e as i32+1)'
        if expression is not None:
            lines.append(f'        {field}: {expression},')
    # The upstream proto omits the Thrift signal request-ID field.
    unused = set(fields)-used
    if unused - ({'request_id'} if name=='WorkflowExecutionSignaledEventAttributes' else set()):
        raise RuntimeError(f'Unmapped Rust fields in {name}: {unused}')
    out.extend([f'fn {snake(name)}(v:{namespace}::{name}) -> p::{name} {{', f'    p::{name} {{', *lines, *(['        ..Default::default()'] if len(lines) != len(re.findall(r'^  ([\w.]+|map<[^>]+>) (\w+) = \d+', body, re.M)) else []), '    }', '}'])
out.extend(['pub fn event(v:st::HistoryEvent) -> Result<p::HistoryEvent,Status> {', '    let attributes=match v.event_type {'])
for name in attrs:
    event = name.removesuffix('EventAttributes')
    field = snake(name)
    out.append(f'        Some(EventType::{event}) => v.{field}.map({field}).map(p::history_event::Attributes::{name}),')
out.extend(['        _=>return Err(Status::unimplemented("This history event type has not been ported.")),', '    }.ok_or_else(||Status::internal("History event attributes are missing."))?;', '    Ok(p::HistoryEvent {event_id:v.event_id,event_time:v.timestamp.map(timestamp),version:v.version,task_id:v.task_id,attributes:Some(attributes)})', '}'])
path=ROOT/'rust/crates/cadence-server/src/grpc_history.rs'
path.write_text('\n'.join(out)+'\n')
import subprocess
subprocess.run(['rustfmt','--edition','2021',str(path)],check=True)
