#!/usr/bin/env python3
"""Generate proto -> internal history event converters (client direction).

Inverse of generate-grpc-history.py (Go common/types/mapper/proto/api.go
`ToHistoryEvent`). Output: rust/crates/cadence-proto/src/convert/history_in.rs,
declared with #[rustfmt::skip] so it needs no local rustfmt.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
structs = {}
for source in (ROOT / 'rust/crates/cadence-api/src').glob('*.rs'):
    for name, body in re.findall(r'pub struct (\w+) \{(.*?)\n\}', source.read_text(), re.S):
        fields = dict(re.findall(r'pub (\w+):\s*([^\n]+)', body))
        structs[name] = (source.stem, {k: v.rstrip(',').strip() for k, v in fields.items()})
proto = (ROOT / 'go/idls/proto/uber/cadence/api/v1/history.proto').read_text()
messages = dict(re.findall(r'message (\w+) \{(.*?)\n\}', proto, re.S))


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def inner(ft):
    m = re.match(r'Option<(.*)>$', ft)
    return m.group(1) if m else ft


out = ['// Generated by rust/tools/generate-grpc-history-in.py; do not hand edit.',
       '// Inverse of history.rs; mirrors Go common/types/mapper/proto/api.go To* mappers.',
       '#![allow(clippy::needless_update, clippy::useless_conversion, clippy::unnecessary_cast)]',
       'use super::*;',
       'use crate::api as p;',
       'use cadence_api::{enums, service_types as st, tasks};',
       'use tonic::Status;',
       '// Remote clusters speak Thrift-style unix nanoseconds (Go time.UnixNano).','fn millis(t: prost_types::Timestamp) -> i64 { t.seconds.saturating_mul(1_000_000_000).saturating_add(i64::from(t.nanos)) }',
       'fn secs64(v: Option<prost_types::Duration>) -> Result<Option<i64>, Status> { Ok(seconds(v)?.map(i64::from)) }',
       ]
attrs = []
for name, body in messages.items():
    if not name.endswith('EventAttributes') or name not in structs:
        continue
    module, fields = structs[name]
    namespace = 'st' if module == 'service_types' else 'tasks'
    attrs.append((name, namespace))
    lines = []
    pre = []
    fields_proto = re.findall(r'^  ([\w.]+|map<[^>]+>) (\w+) = \d+', body, re.M)
    for typ, field in fields_proto:
        ft = None
        if typ == 'Failure':
            prefix = {'continued_failure': 'continued_failure_', 'last_failure': 'last_failure_'}.get(field, '')
            reason, details = prefix + 'reason', prefix + 'details'
            if field == 'failure' and 'failure_reason' in fields:
                reason, details = 'failure_reason', 'failure_details'
            options = prefix + 'options' if prefix else 'failure_options'
            if reason in fields:
                pre.append(f'let (r_{field}, d_{field}, o_{field}) = failure_in(v.{field})?;')
                lines.append(f'{reason}: ' + (f'r_{field}' if fields[reason].startswith('Option') else f'r_{field}.unwrap_or_default()') + ',')
                if details in fields:
                    lines.append(f'{details}: d_{field},')
                if options in fields:
                    lines.append(f'{options}: o_{field},')
            continue
        if typ == 'ParentExecutionInfo':
            pre.append('let parent = v.parent_execution_info;')
            lines += ['parent_workflow_domain: parent.as_ref().map(|x| x.domain_name.clone()),',
                      'parent_workflow_execution: parent.as_ref().and_then(|x| x.workflow_execution.clone()).map(execution),',
                      'parent_initiated_event_id: parent.as_ref().map(|x| x.initiated_id),']
            continue
        if typ == 'ExternalExecutionInfo':
            pre.append('let external = v.external_execution_info;')
            lines += ['external_workflow_execution: external.as_ref().and_then(|x| x.workflow_execution.clone()).map(execution),',
                      'external_initiated_event_id: external.as_ref().map(|x| x.initiated_id),']
            continue
        aliases = {'expiration_time': 'expiration_timestamp', 'first_scheduled_time': 'first_scheduled_time_nano',
                   'first_run_at': 'first_run_at_timestamp', 'backoff_start_interval': 'backoff_start_interval_in_seconds'}
        source = aliases.get(field, field)
        if typ == 'google.protobuf.Duration' and source not in fields:
            source += '_seconds'
        if source not in fields:
            continue
        ft = fields[source]
        opt = ft.startswith('Option')
        it = inner(ft)
        f = f'v.{field}'
        if typ == 'Payload':
            e = f'Some(data({f}))' if opt else f'data({f})'
        elif typ == 'bytes':
            e = f'Some({f})' if opt else f
        elif typ == 'google.protobuf.Duration':
            if it == 'i64':
                e = f'secs64({f})?'
            else:
                e = f'seconds({f})?' if opt else f'seconds({f})?.unwrap_or_default()'
        elif typ == 'google.protobuf.Timestamp':
            e = f'nanos({f})' if source.endswith('_nano') else f'{f}.map(millis)'
        elif typ == 'WorkflowType':
            e = f'{f}.map(|x| t::WorkflowType {{ name: x.name }})'
        elif typ == 'ActivityType':
            e = f'{f}.map(|x| t::ActivityType {{ name: x.name }})'
        elif typ == 'TaskList':
            e = f'{f}.map(task_list).transpose()?'
        elif typ == 'WorkflowExecution':
            e = f'{f}.map(execution)'
        elif typ == 'RetryPolicy':
            e = f'{f}.map(retry).transpose()?'
        elif typ == 'Memo':
            e = f'{f}.map(memo_in)'
        elif typ == 'Header':
            e = f'{f}.map(header_in)'
        elif typ == 'SearchAttributes':
            e = f'{f}.map(search_attributes_in)'
        elif typ.startswith('map<'):
            e = f'Some({f})' if opt else f
        elif typ in ('string', 'bool'):
            e = f'Some({f})' if opt else f
        elif typ in ('int64', 'int32'):
            want = 'i64' if typ == 'int64' else 'i32'
            val = f if it == want else f'{f} as {it}'
            e = f'Some({val})' if opt else val
        else:
            # protobuf enum
            if opt:
                e = f'enum_in({f}, enums::{it}::from_i32)?'
            else:
                e = f'enum_in({f}, enums::{it}::from_i32)?.unwrap_or_default()'
        lines.append(f'{source}: {e},')
    out.append(f'fn {snake(name)}(v: p::{name}) -> Result<{namespace}::{name}, Status> {{')
    out.extend('    ' + p_ for p_ in pre)
    out.append(f'    Ok({namespace}::{name} {{')
    out.extend('        ' + l for l in lines)
    out.append('        ..Default::default()')
    out.append('    })')
    out.append('}')

out.append('pub fn event(v: p::HistoryEvent) -> Result<st::HistoryEvent, Status> {')
out.append('    let mut out = st::HistoryEvent { event_id: v.event_id, timestamp: v.event_time.map(millis), version: v.version, task_id: v.task_id, ..Default::default() };')
out.append('    match v.attributes {')
for name, namespace in attrs:
    event = name.removesuffix('Attributes')[:-len('Event')] if False else name.removesuffix('EventAttributes')
    out.append(f'        Some(p::history_event::Attributes::{name}(a)) => {{ out.event_type = Some(enums::EventType::{event}); out.{snake(name)} = Some({snake(name)}(a)?); }}')
out.append('        Some(_) => return Err(Status::unimplemented("This history event type has not been ported.")),')
out.append('        None => return Err(Status::internal("History event attributes are missing.")),')
out.append('    }')
out.append('    Ok(out)')
out.append('}')
path = ROOT / 'rust/crates/cadence-proto/src/convert/history_in.rs'
path.write_text('\n'.join(out) + '\n')
print(len(attrs), 'attribute types')
