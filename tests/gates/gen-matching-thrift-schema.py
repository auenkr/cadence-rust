#!/usr/bin/env python3
"""Generate rust/crates/cadence-matching/src/thrift_matching_schema.rs from the Go generated
thrift decoders (go/.gen/go/{shared,matching}). For every struct reachable from the ten Matching
request structs it records field id -> wire type (+ nested struct / container element types), which
is exactly what Go's generated `FromWire` checks (`field.Value.Type() == wire.TX`; mismatches are
skipped, container element-type mismatches return nil)."""
import re, sys
root = sys.argv[1]  # repo root
W = {'TBool': 2, 'TI8': 3, 'TDouble': 4, 'TI16': 6, 'TI32': 8, 'TI64': 10, 'TBinary': 11,
     'TStruct': 12, 'TMap': 13, 'TSet': 14, 'TList': 15}
src = {}
for pkg in ('shared', 'matching'):
    src[pkg] = open(f'{root}/go/.gen/go/{pkg}/{pkg}.go').read()

def funcs(text):
    return {m.group(1): m for m in re.finditer(r'^func (\S+?)\(', text, re.M)}

def body(text, header_re):
    m = re.search(header_re, text, re.M)
    if not m:
        return None
    i = text.index('{', m.end() - 1)
    d = 0
    for j in range(i, len(text)):
        if text[j] == '{': d += 1
        elif text[j] == '}':
            d -= 1
            if d == 0:
                return text[m.start():j + 1]

def read_sig(pkg, name):
    """_Name_Read return -> ('struct', 'pkg.Type') or ('scalar', None)."""
    m = re.search(r'^func _%s_Read\(w wire\.Value\) \((\*?)([\w.]+), error\)' % name, src[pkg], re.M)
    if not m:
        return None
    if m.group(1) != '*':
        return ('scalar', None)
    t = m.group(2)
    return ('struct', t if '.' in t else f'{pkg}.{t}')

def helper(pkg, name):
    b = body(src[pkg], r'^func %s\(' % name)
    assert b, (pkg, name)
    return b

def elem_struct(pkg, hb, var):
    m = re.search(r'_(\w+)_Read\(%s\)' % var, hb)
    if not m: return None
    sg = read_sig(pkg, m.group(1))
    return sg[1] if sg and sg[0] == 'struct' else None

structs = {}
def parse(pkg, name):
    key = f'{pkg}.{name}'
    if key in structs: return
    b = body(src[pkg], r'^func \(v \*%s\) FromWire\(' % name)
    assert b, key
    out = []
    structs[key] = out
    for cm in re.finditer(r'\t\tcase (\d+):\n\t\t\tif field\.Value\.Type\(\) == wire\.(\w+) \{(.*?)\n\t\t\t\}\n(?=\t\tcase|\t\t\})', b, re.S):
        fid, wt, blk = int(cm.group(1)), cm.group(2), cm.group(3)
        inner = ('n',)
        rm = re.search(r'(\w+)\s*(?:,\s*err)?\s*=\s*_(\w+)_Read\(field\.Value(\.GetList\(\)|\.GetMap\(\)|\.GetSet\(\))?\)', blk)
        if rm is None:
            rm = re.search(r'=\s*_(\w+)_Read\(field\.Value(\.GetList\(\)|\.GetMap\(\)|\.GetSet\(\))?\)', blk)
            rn, suf = (rm.group(1), rm.group(2)) if rm else (None, None)
        else:
            rn, suf = rm.group(2), rm.group(3)
        if rn is None:
            pass  # scalar read
        elif suf is None:
            sg = read_sig(pkg, rn)
            if sg and sg[0] == 'struct':
                inner = ('s', sg[1])
                parse(*sg[1].split('.'))
        else:
            hb = helper(pkg, f'_{rn}_Read')
            if suf == '.GetMap()':
                kt = W[re.search(r'KeyType\(\) != wire\.(\w+)', hb).group(1)]
                vt = W[re.search(r'ValueType\(\) != wire\.(\w+)', hb).group(1)]
                es = elem_struct(pkg, hb, r'x\.Value')
                assert vt not in (13, 14, 15) or es is None and vt == 15 and False, rn
                inner = ('m', kt, vt, es)
            else:
                et = W[re.search(r'ValueType\(\) != wire\.(\w+)', hb).group(1)]
                assert et not in (13, 14, 15), rn
                es = elem_struct(pkg, hb, 'x')
                inner = ('l', et, es)
            if inner[-1]:
                parse(*inner[-1].split('.'))
        out.append((fid, W[wt], inner))

roots = ['PollForDecisionTaskRequest', 'PollForActivityTaskRequest', 'AddDecisionTaskRequest',
         'AddActivityTaskRequest', 'QueryWorkflowRequest', 'RespondQueryTaskCompletedRequest',
         'CancelOutstandingPollRequest', 'DescribeTaskListRequest', 'ListTaskListPartitionsRequest']
for r in roots:
    parse('matching', r)
parse('shared', 'GetTaskListsByDomainRequest')  # MatchingService uses the shared request type

def rs(inner):
    if inner[0] == 'n': return 'Inner::None'
    if inner[0] == 's': return f'Inner::Struct("{inner[1]}")'
    if inner[0] == 'l': return 'Inner::List(%d, %s)' % (inner[1], f'Some("{inner[2]}")' if inner[2] else 'None')
    return 'Inner::Map(%d, %d, %s)' % (inner[1], inner[2], f'Some("{inner[3]}")' if inner[3] else 'None')

o = ['// @generated by tests/gates/gen-matching-thrift-schema.py from go/.gen/go/{shared,matching}.',
     '// Field id -> Thrift wire type for every struct reachable from the Matching request structs.',
     '#![allow(clippy::all)]',
     'pub enum Inner { None, Struct(&\'static str), List(u8, Option<&\'static str>), Map(u8, u8, Option<&\'static str>) }',
     'pub type Fields = &\'static [(i16, u8, Inner)];',
     'pub fn fields(name: &str) -> Option<Fields> {', '    Some(match name {']
for k in sorted(structs):
    o.append(f'        "{k}" => &[')
    for fid, wt, inner in sorted(structs[k]):
        o.append(f'            ({fid}, {wt}, {rs(inner)}),')
    o.append('        ],')
o += ['        _ => return None,', '    })', '}']
open(f'{root}/rust/crates/cadence-matching/src/thrift_matching_schema.rs', 'w').write('\n'.join(o) + '\n')
print(len(structs), 'structs')
